static void build_json_status(char *buf, int bufsz) {
    char loaded_name[128] = "none";
    if (s_loaded_index < s_image_count) {
        const char *p = s_image_paths[s_loaded_index];
        const char *sl = strrchr(p, '/');
        strncpy(loaded_name, sl ? sl + 1 : p, sizeof(loaded_name) - 1);
    }

    char loaded_esc[128];
    json_escape(loaded_esc, sizeof(loaded_esc), loaded_name);

    int pos = snprintf(buf, bufsz,
        "HTTP/1.1 200 OK\r\n"
        "Content-Type: application/json\r\n"
        "Connection: close\r\n\r\n"
        "{\"ok\":true,\"state\":\"%s\",\"state_id\":%d,"
        "\"loaded_index\":%lu,\"loaded_name\":\"%s\","
        "\"image_count\":%lu,\"ip\":\"%s\"",
        state_name(commo_bridge_get_drive_state()), commo_bridge_get_drive_state(),
        (unsigned long)s_loaded_index, loaded_esc,
        (unsigned long)s_image_count, s_ip_str);

    uint64_t sd_used = 0, sd_total = 0;
    if (sd_get_space(&sd_used, &sd_total)) {
        snprintf(buf + pos, bufsz - pos,
            ",\"sd_used_mb\":%lu,\"sd_total_mb\":%lu"
            ",\"page_offset\":%lu,\"page_count\":%lu,\"total_count\":%lu}",
            (unsigned long)(sd_used  / (1024 * 1024)),
            (unsigned long)(sd_total / (1024 * 1024)),
            (unsigned long)s_ws_page_offset,
            (unsigned long)s_ws_page_count,
            (unsigned long)s_ws_total_count);
    } else {
        snprintf(buf + pos, bufsz - pos,
            ",\"page_offset\":%lu,\"page_count\":%lu,\"total_count\":%lu}",
            (unsigned long)s_ws_page_offset,
            (unsigned long)s_ws_page_count,
            (unsigned long)s_ws_total_count);
    }
}

// ---------------------------------------------------------------------------
// Handle HTTP request line
// ---------------------------------------------------------------------------
// Returns the response as a static buffer or NULL to stream a file.
// 'conn' holds the accumulated request.

// S3: constant-time 33-byte token comparison (including NUL) to prevent
// timing-oracle attacks on the firmware-flash authorisation token.
static bool token_equal_ct(const char *a, const char *b) {
    unsigned int diff = 0;
    for (int i = 0; i < 33; i++)
        diff |= (unsigned char)a[i] ^ (unsigned char)b[i];
    return diff == 0;
}

static void handle_request(struct tcp_pcb *pcb, http_conn_t *conn) {
    char *req   = conn->request;
    bool  is_get  = (strncmp(req, "GET ",  4) == 0);
    bool  is_post = (strncmp(req, "POST ", 5) == 0);
    if (!is_get && !is_post) {
        static const char *m405 =
            "HTTP/1.1 405 Method Not Allowed\r\n"
            "Allow: GET, POST\r\nConnection: close\r\n\r\n";
        wolfSSL_write(conn->ssl, m405, (int)strlen(m405));
        return;
    }
    char *path_start = req + (is_get ? 4 : 5);
    char  path[256]  = "";

    // Extract URL path (up to space or \r\n)
    int i = 0;
    while (path_start[i] && path_start[i] != ' ' && path_start[i] != '\r'
           && i < 255) {
        path[i] = path_start[i];
        i++;
    }
    path[i] = '\0';

    LOG_INFO_MSG("HTTP", "%s %s", is_get ? "GET" : "POST", path);

    // ── GET / ── Main HTML page
    if (is_get && (strcmp(path, "/") == 0 || strcmp(path, "/index.html") == 0)) {
        const char *html = build_html_page();
        int total = (int)strlen(html);
        int sent  = 0;
        while (sent < total) {
            int chunk = total - sent;
            if (chunk > 4096) chunk = 4096;
            int wr;
            int retries = 0;
            do {
                wr = wolfSSL_write(conn->ssl, html + sent, chunk);
                if (wr <= 0) {
                    if (wolfSSL_get_error(conn->ssl, wr) != WOLFSSL_ERROR_WANT_WRITE)
                        goto html_done;
                    cyw43_arch_poll();
                }
            } while (wr <= 0 && ++retries < 20);
            if (wr <= 0) break;
            sent += wr;
        }
        html_done:;
        return;
    }

    // ── GET /api/status ── JSON status
    if (is_get && strcmp(path, "/api/status") == 0) {
        build_json_status(conn->resp_buf, sizeof(conn->resp_buf));
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── GET /api/images ── JSON image list
    if (is_get && strcmp(path, "/api/images") == 0) {
        int pos = snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n[");
        for (uint32_t j = 0; j < s_image_count && j < 99; j++) {
            char base[MAX_PATH_LEN], base_esc[256], cp[256] = "";
            basename_no_ext(s_image_paths[j], base, sizeof(base));
            json_escape(base_esc, sizeof(base_esc), base);
            bool hc = cover_exists(s_image_paths[j], cp, sizeof(cp));
            pos += snprintf(conn->resp_buf + pos, sizeof(conn->resp_buf) - pos,
                "%s{\"index\":%lu,\"name\":\"%s\",\"has_cover\":%s,\"loaded\":%s}",
                j > 0 ? "," : "",
                (unsigned long)j, base_esc,
                hc ? "true" : "false",
                (j == s_loaded_index) ? "true" : "false");
        }
        pos += snprintf(conn->resp_buf + pos, sizeof(conn->resp_buf) - pos, "]");
        wolfSSL_write(conn->ssl, conn->resp_buf, pos);
        return;
    }

    // ── POST /api/load/{index} ── Load a disc
    if (is_post && strncmp(path, "/api/load/", 10) == 0) {
        char *endp;
        unsigned long idx_ul = strtoul(path + 10, &endp, 10);
        uint32_t idx = (endp == path + 10 || idx_ul > UINT32_MAX) ? UINT32_MAX : (uint32_t)idx_ul;
        if (idx < s_image_count) {
            s_load_index   = idx;
            s_load_pending = true;
            LOG_INFO_MSG("HTTP", "web load request: image %lu", (unsigned long)idx);
            snprintf(conn->resp_buf, sizeof(conn->resp_buf),
                "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
                "Connection: close\r\n\r\n"
                "{\"ok\":true,\"index\":%lu}", (unsigned long)idx);
        } else {
            snprintf(conn->resp_buf, sizeof(conn->resp_buf),
                "HTTP/1.1 400 Bad Request\r\nContent-Type: application/json\r\n"
                "Connection: close\r\n\r\n"
                "{\"ok\":false,\"error\":\"index out of range\"}");
        }
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── POST /api/page/next or /api/page/prev ── Paginate image list
    if (is_post && strcmp(path, "/api/page/next") == 0) {
        s_page_delta   = +1;
        s_page_request = true;
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true,\"direction\":\"next\"}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }
    if (is_post && strcmp(path, "/api/page/prev") == 0) {
        s_page_delta   = -1;
        s_page_request = true;
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true,\"direction\":\"prev\"}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── POST /api/eject ── Eject disc
    if (is_post && strcmp(path, "/api/eject") == 0) {
        s_load_index   = UINT32_MAX;
        s_load_pending = true;
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── POST /api/carousel/next | /api/carousel/prev ── advance the carousel
    if (is_post && strcmp(path, "/api/carousel/next") == 0) {
        s_carousel_delta = +1; s_carousel_request = true;
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true,\"direction\":\"next\"}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }
    if (is_post && strcmp(path, "/api/carousel/prev") == 0) {
        s_carousel_delta = -1; s_carousel_request = true;
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true,\"direction\":\"prev\"}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── POST /api/playlist/all ── switch carousel back to all discs
    if (is_post && strcmp(path, "/api/playlist/all") == 0) {
        s_playlist_name[0] = '\0';      // "" = all discs
        s_playlist_request = true;
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true,\"source\":\"all\"}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── POST /api/playlist/set/{name} ── activate playlist <name>.m3u
    // {name} becomes part of a file path (0:/playlists/<name>.m3u), so it is
    // validated against path-traversal: no '/', '\\', or ".." and length-bounded.
    if (is_post && strncmp(path, "/api/playlist/set/", 18) == 0) {
        const char *name = path + 18;
        size_t nlen = strlen(name);
        bool safe = (nlen > 0 && nlen < sizeof(s_playlist_name) &&
                     !strchr(name, '/') && !strchr(name, '\\') && !strstr(name, ".."));
        if (!safe) {
            snprintf(conn->resp_buf, sizeof(conn->resp_buf),
                "HTTP/1.1 400 Bad Request\r\nContent-Type: application/json\r\n"
                "Connection: close\r\n\r\n{\"ok\":false,\"error\":\"bad name\"}");
        } else {
            snprintf(s_playlist_name, sizeof(s_playlist_name), "%s", name);
            s_playlist_request = true;
            snprintf(conn->resp_buf, sizeof(conn->resp_buf),
                "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
                "Connection: close\r\n\r\n{\"ok\":true}");
        }
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── GET /api/playlist/list ── List .m3u playlists in 0:/playlists/
    // Names are returned base-only (no dir, no ".m3u") so each maps directly to
    // POST /api/playlist/set/{name}.  A missing playlists dir yields [].
    if (is_get && strcmp(path, "/api/playlist/list") == 0) {
        static char pl_paths[8][MAX_PATH_LEN];  // off the lwIP callback stack
        uint32_t n = sd_scan_m3u_files(pl_paths, 8, "0:/playlists/", 0);
        int pos = snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"playlists\":[");
        for (uint32_t j = 0; j < n && pos < (int)sizeof(conn->resp_buf) - 4; j++) {
            char base[MAX_PATH_LEN];
            basename_no_ext(pl_paths[j], base, sizeof(base));
            char esc[MAX_PATH_LEN * 2];
            json_escape(esc, sizeof(esc), base);
            pos += snprintf(conn->resp_buf + pos, sizeof(conn->resp_buf) - pos,
                "%s\"%s\"", j ? "," : "", esc);
        }
        snprintf(conn->resp_buf + pos, sizeof(conn->resp_buf) - pos, "]}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── GET /api/fw/list ── List .uf2 firmware files on SD root
    if (is_get && strcmp(path, "/api/fw/list") == 0) {
        static char fw_paths[8][MAX_PATH_LEN];  // O1: 2 KB off the lwIP callback stack
        uint32_t n = sd_scan_uf2_files(fw_paths, 8, "0:/", 0);
        int pos = snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"files\":[");
        for (uint32_t j = 0; j < n && pos < (int)sizeof(conn->resp_buf) - 4; j++) {
            // Strip the "0:/" prefix for the client
            const char *name = fw_paths[j];
            if (name[0] == '0' && name[1] == ':' && name[2] == '/') name += 3;
            char esc[MAX_PATH_LEN * 2];
            json_escape(esc, sizeof(esc), name);
            pos += snprintf(conn->resp_buf + pos, sizeof(conn->resp_buf) - pos,
                "%s\"%s\"", j ? "," : "", esc);
        }
        snprintf(conn->resp_buf + pos, sizeof(conn->resp_buf) - pos, "]}");
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── POST /api/fw/flash/{filename} ── Validate + flash UF2 from SD root
    if (is_post && strncmp(path, "/api/fw/flash/", 14) == 0) {
        // Validate firmware-flash token before doing anything else.
        char provided_token[33] = "";
        extract_request_token(req, path, provided_token, sizeof(provided_token));
        if (s_fw_token[0] == '\0' || !token_equal_ct(provided_token, s_fw_token)) {
            static const char *unauth =
                "HTTP/1.1 403 Forbidden\r\nContent-Type: application/json\r\n"
                "Connection: close\r\n\r\n"
                "{\"ok\":false,\"error\":\"invalid or missing fw_token\"}";
            wolfSSL_write(conn->ssl, unauth, (int)strlen(unauth));
            return;
        }

        // Strip query string from fname before filename validation.
        const char *fname_raw = path + 14;
        char fname[MAX_PATH_LEN];
        size_t fn_max = sizeof(path) - 14U - 1U; // bytes remaining in path[] after prefix
        size_t fn_len = 0;
        while (fname_raw[fn_len] && fname_raw[fn_len] != '?' && fn_len < fn_max)
            fn_len++;
        memcpy(fname, fname_raw, fn_len);
        fname[fn_len] = '\0';

        // Bounds first (cheapest checks), then string content.
        // Blocks: empty, oversized (headroom for "0:/" prefix), path traversal (..),
        // path separators (/ and \), and percent-encoded sequences (%2e%2e bypasses
        // the ".." check — same defence as the /covers/ endpoint).
        if (fn_len == 0 || fn_len >= (size_t)(MAX_PATH_LEN - 3) ||
            strstr(fname, "..") || strchr(fname, '/') ||
            strchr(fname, '\\') || strchr(fname, '%')) {
            static const char *bad =
                "HTTP/1.1 400 Bad Request\r\nContent-Type: application/json\r\n"
                "Connection: close\r\n\r\n{\"ok\":false,\"error\":\"invalid filename\"}";
            wolfSSL_write(conn->ssl, bad, (int)strlen(bad));
            return;
        }
        char full_path[3 + MAX_PATH_LEN + 1];
        snprintf(full_path, sizeof(full_path), "0:/%s", fname);
        // Acknowledge before the blocking flash operation; tcp_output flushes it
        static const char *ack =
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":true,\"msg\":\"flashing\"}";
        wolfSSL_write(conn->ssl, ack, (int)strlen(ack));
        tcp_output(pcb);   // flush ack immediately — reboot follows
        // fw_flash_and_reboot never returns on success; returns error code on failure
        fw_result_t fr = fw_flash_and_reboot(full_path);
        snprintf(conn->resp_buf, sizeof(conn->resp_buf),
            "HTTP/1.1 500 Internal Server Error\r\n"
            "Content-Type: application/json\r\n"
            "Connection: close\r\n\r\n{\"ok\":false,\"error\":\"%s\"}",
            fw_result_str(fr));
        wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
        return;
    }

    // ── GET /covers/{name}.jpg ── Serve cover art from SD card
    if (is_get && strncmp(path, "/covers/", 8) == 0) {
        // Sanitise: only a bare filename is permitted — no path separators,
        // no "..", and no percent-encoded sequences (%2e%2e bypasses ".." check).
        const char *cover_name = path + 8;
        if (strstr(cover_name, "..") || strchr(cover_name, '/') ||
            strchr(cover_name, '\\') || strchr(cover_name, '%')) {
            static const char *forbidden =
                "HTTP/1.1 403 Forbidden\r\nConnection: close\r\n\r\n";
            wolfSSL_write(conn->ssl, forbidden, (int)strlen(forbidden));
            return;
        }

        char sd_path[264];
        snprintf(sd_path, sizeof(sd_path), "0:/covers/%s", cover_name);

        FIL cover_file;
        FRESULT fr = f_open(&cover_file, sd_path, FA_READ);
        if (fr == FR_OK) {
            FSIZE_t fsize = f_size(&cover_file);
            // Send HTTP header
            int hlen = snprintf(conn->resp_buf, sizeof(conn->resp_buf),
                "HTTP/1.1 200 OK\r\n"
                "Content-Type: image/jpeg\r\n"
                "Content-Length: %lu\r\n"
                "Cache-Control: max-age=3600\r\n"
                "Connection: close\r\n\r\n",
                (unsigned long)fsize);
            wolfSSL_write(conn->ssl, conn->resp_buf, hlen);

            // Stream file in 512-byte chunks; retry on WANT_WRITE (TLS send buffer full)
            static uint8_t chunk[512];
            UINT br;
            while (f_read(&cover_file, chunk, sizeof(chunk), &br) == FR_OK && br > 0) {
                int wr = WOLFSSL_FATAL_ERROR;
                for (int retries = 0; retries < 20 && wr <= 0; retries++) {
                    wr = wolfSSL_write(conn->ssl, chunk, (int)br);
                    if (wr <= 0) {
                        int we = wolfSSL_get_error(conn->ssl, wr);
                        if (we != WOLFSSL_ERROR_WANT_WRITE) goto cover_done;
                        cyw43_arch_poll();
                    }
                }
                if (wr <= 0) break;
            }
            cover_done:
            f_close(&cover_file);
            return;
        }

        // Cover not found — return 404 with generic CD SVG
        static const char *not_found =
            "HTTP/1.1 404 Not Found\r\n"
            "Content-Type: image/svg+xml\r\n"
            "Cache-Control: max-age=60\r\n"
            "Connection: close\r\n\r\n"
            "<svg xmlns='http://www.w3.org/2000/svg' width='200' height='200'>"
            "<rect width='200' height='200' fill='#0f3460' rx='8'/>"
            "<circle cx='100' cy='100' r='75' fill='#1a1a4e' stroke='#c8a000' stroke-width='2'/>"
            "<circle cx='100' cy='100' r='15' fill='#0f3460' stroke='#888' stroke-width='1'/>"
            "<text x='100' y='170' text-anchor='middle' fill='#888' "
            "font-family='system-ui' font-size='12'>No Cover Art</text>"
            "</svg>";
        wolfSSL_write(conn->ssl, not_found, (int)strlen(not_found));
        return;
    }

    // ── 404 fallback ──
    // Sanitise path: strip non-printable bytes before reflecting into response.
    char safe_path[256];
    size_t sp = 0;
    for (const char *c = path; *c && sp < sizeof(safe_path) - 1; c++)
        safe_path[sp++] = (*c >= 0x20 && *c < 0x7f) ? *c : '?';
    safe_path[sp] = '\0';
    snprintf(conn->resp_buf, sizeof(conn->resp_buf),
        "HTTP/1.1 404 Not Found\r\nContent-Type: text/plain\r\n"
        "Connection: close\r\n\r\nNot found: %s", safe_path);
    wolfSSL_write(conn->ssl, conn->resp_buf, (int)strlen(conn->resp_buf));
}

// ---------------------------------------------------------------------------
// TLS receive callback — called by LwIPNativeReceiveCB after it buffers the pbuf.
// arg = conn (stored in nlwip->arg by wolfSSL_SetIO_LwIP).
// ---------------------------------------------------------------------------
static err_t tls_recv_fn(void *arg, struct tcp_pcb *pcb,
                          struct pbuf *p, err_t err) {
    http_conn_t *conn = (http_conn_t *)arg;

    if (!p || err != ERR_OK) {
        tcp_close(pcb);
        conn_free(conn);
        return ERR_OK;
    }

    // Advance receive window. LwIPNativeReceiveCB only calls tcp_recved for
    // chained (2nd+) pbufs — we must cover the first pbuf here.
    tcp_recved(pcb, p->tot_len);

    // Phase 1: drive TLS handshake until WOLFSSL_SUCCESS.
    // wolfSSL_accept is non-blocking; WANT_READ means come back when more data arrives.
    if (!conn->tls_ready) {
        int r = wolfSSL_accept(conn->ssl);
        if (r != WOLFSSL_SUCCESS) {
            int e = wolfSSL_get_error(conn->ssl, r);
            if (e == WOLFSSL_ERROR_WANT_READ || e == WOLFSSL_ERROR_WANT_WRITE)
                return ERR_OK;  // normal — wait for next packet
            printf("[WEB] TLS handshake error %d\n", e);
            tcp_close(pcb);
            conn_free(conn);
            return ERR_OK;
        }
        conn->tls_ready = true;
    }

    // Phase 2: handshake done — read plaintext HTTP request.
    int n = wolfSSL_read(conn->ssl,
                         conn->request + conn->req_len,
                         (int)sizeof(conn->request) - 1 - conn->req_len);
    if (n > 0) {
        conn->req_len += n;
        conn->request[conn->req_len] = '\0';
    }

    // Dispatch once we have a complete HTTP header.
    if (conn->req_len > 0 && strstr(conn->request, "\r\n\r\n")) {
        handle_request(pcb, conn);
        tcp_output(pcb);
        tcp_close(pcb);
        conn_free(conn);
    }
    return ERR_OK;
}

static err_t tcp_accept_cb(void *arg, struct tcp_pcb *new_pcb, err_t err) {
    (void)arg;
    if (err != ERR_OK || !new_pcb) return ERR_VAL;

    http_conn_t *conn = conn_alloc();
    if (!conn) {
        tcp_close(new_pcb);
        return ERR_MEM;
    }

    conn->ssl = wolfSSL_new(s_tls_ctx);
    if (!conn->ssl) {
        conn_free(conn);
        tcp_close(new_pcb);
        return ERR_MEM;
    }

    // wolfSSL_SetIO_LwIP installs LwIPNativeReceiveCB as the lwIP recv callback,
    // sets tcp_arg to &ssl->lwipCtx, and stores tls_recv_fn + conn in nlwip.
    wolfSSL_SetIO_LwIP(conn->ssl, new_pcb, tls_recv_fn, NULL, conn);
    tcp_setprio(new_pcb, TCP_PRIO_MIN);  // Low priority vs bus handler

    return ERR_OK;
}

// ---------------------------------------------------------------------------
// webserver_init
// ---------------------------------------------------------------------------
bool webserver_init(void) {
    read_wifi_config();

    if (s_ssid[0] == '\0') {
        printf("[WEB] No wifi_ssid in nebula32.cfg — WiFi disabled\n"
               "[WEB] Add these lines to enable:\n"
               "      wifi_ssid     = YourNetworkName\n"
               "      wifi_password = YourPassword\n");
        return false;
    }

    // Generate and persist a firmware-flash token if none is configured.
    // The token is appended to nebula32.cfg and visible to whoever has SD access.
#ifndef WEBSERVER_TEST_BUILD
    if (s_fw_token[0] == '\0') {
        generate_and_save_token();
        printf("[WEB] fw_token generated: %s\n"
               "[WEB] Copy this value from nebula32.cfg to authorise firmware flashing.\n",
               s_fw_token);
    }
#endif

    printf("[WEB] Connecting to WiFi SSID: %s ...\n", s_ssid);
    LOG_INFO_MSG("WEB ", "connecting to SSID: %s", s_ssid);

    // Initialise WiFi in poll mode (no RTOS required)
    if (cyw43_arch_init()) {
        printf("[WEB] CYW43 init failed\n");
        LOG_ERROR_MSG("WiFi CYW43 init failed");
        return false;
    }

    cyw43_arch_enable_sta_mode();

    // Connect (timeout: 30 seconds)
    if (cyw43_arch_wifi_connect_timeout_ms(s_ssid, s_pass,
                                            CYW43_AUTH_WPA2_AES_PSK,
                                            30000) != 0) {
        printf("[WEB] WiFi connection failed (wrong password or SSID?)\n");
        LOG_ERROR_MSG("WiFi connection failed (SSID=%s)", s_ssid);
        return false;
    }

    // Get IP address
    ip4_addr_t *ip = &cyw43_state.netif[0].ip_addr;
    snprintf(s_ip_str, sizeof(s_ip_str), "%s", ip4addr_ntoa(ip));
    printf("[WEB] Connected! IP: %s\n", s_ip_str);
    LOG_INFO_MSG("WEB ", "WiFi connected, IP=%s", s_ip_str);

    // wolfSSL deliberately uses the default SRAM heap, NOT psram_alloc:
    // the PSRAM bump allocator never reclaims (psram_free is a mark-only
    // no-op), but wolfSSL mallocs/frees on every TLS handshake — routing it
    // there leaked PSRAM per HTTPS connection until psram_alloc returned
    // NULL and TLS died.  If SRAM pressure returns, the correct fix is
    // WOLFSSL_STATIC_MEMORY with a fixed PSRAM arena that wolfSSL manages
    // internally — not wolfSSL_SetAllocators over the bump allocator.

    // Initialise wolfSSL TLS context (once per boot)
    wolfSSL_Init();
    s_tls_ctx = wolfSSL_CTX_new(wolfTLSv1_3_server_method());
    if (!s_tls_ctx) {
        printf("[WEB] wolfSSL_CTX_new failed\n");
        return false;
    }
    // Load TLS certificate — SD card takes priority; compiled-in cert is the fallback.
    // SD card paths: 0:/certs/nebula32.crt.der + 0:/certs/nebula32.key.der
    // Compiled-in fallback: include/tls_cert.h (regenerated by tools/gen_tls_cert.sh)
    {
        bool loaded = false;
#ifndef WEBSERVER_TEST_BUILD
        // Attempt to load user cert from SD card (reuse one buffer for cert then key).
        static uint8_t s_cert_buf[1024];
        FIL f; UINT br;
        bool cert_ok = false, key_ok = false;
        if (f_open(&f, "0:/certs/nebula32.crt.der", FA_READ) == FR_OK) {
            if (f_read(&f, s_cert_buf, sizeof(s_cert_buf), &br) == FR_OK && br > 0)
                cert_ok = wolfSSL_CTX_use_certificate_buffer(s_tls_ctx,
                    s_cert_buf, (long)br, SSL_FILETYPE_ASN1) == WOLFSSL_SUCCESS;
            f_close(&f);
        }
        if (cert_ok && f_open(&f, "0:/certs/nebula32.key.der", FA_READ) == FR_OK) {
            if (f_read(&f, s_cert_buf, sizeof(s_cert_buf), &br) == FR_OK && br > 0)
                key_ok = wolfSSL_CTX_use_PrivateKey_buffer(s_tls_ctx,
                    s_cert_buf, (long)br, SSL_FILETYPE_ASN1) == WOLFSSL_SUCCESS;
            f_close(&f);
        }
        if (cert_ok && key_ok) {
            printf("[WEB] TLS cert loaded from SD (0:/certs/nebula32.crt.der)\n");
            loaded = true;
        }
#endif
        if (!loaded) {
            // Compiled-in cert from tls_cert.h (self-signed, generated by tools/gen_tls_cert.sh).
            if (wolfSSL_CTX_use_certificate_buffer(s_tls_ctx,
                    server_ecc_der_256, (long)sizeof_server_ecc_der_256,
                    SSL_FILETYPE_ASN1) != WOLFSSL_SUCCESS ||
                wolfSSL_CTX_use_PrivateKey_buffer(s_tls_ctx,
                    ecc_key_der_256, (long)sizeof_ecc_key_der_256,
                    SSL_FILETYPE_ASN1) != WOLFSSL_SUCCESS) {
                printf("[WEB] TLS cert/key load failed\n");
                wolfSSL_CTX_free(s_tls_ctx);
                s_tls_ctx = NULL;
                return false;
            }
            printf("[WEB] TLS using compiled-in cert (copy certs/*.der to SD for custom cert)\n");
        }
    }

    // Start TLS listener on port 443
    s_listener = tcp_new_ip_type(IPADDR_TYPE_V4);
    if (!s_listener) return false;

    tcp_bind(s_listener, IP_ANY_TYPE, WS_HTTPS_PORT);
    s_listener = tcp_listen_with_backlog(s_listener, 4);
    tcp_accept(s_listener, tcp_accept_cb);

    s_running = true;
    printf("[WEB] HTTPS server running at https://%s/ (self-signed cert)\n", s_ip_str);
    printf("[WEB] Also try: https://%s.local/\n", s_host);
    LOG_INFO_MSG("WEB ", "HTTPS server listening on port %d", WS_HTTPS_PORT);

    return true;
}

