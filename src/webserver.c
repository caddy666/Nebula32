// Filename without extension from a full path
static const char *basename_no_ext(const char *path, char *buf, int bufsz) {
    const char *slash = strrchr(path, '/');
    const char *name  = slash ? slash + 1 : path;
    strncpy(buf, name, bufsz - 1);
    buf[bufsz - 1] = '\0';
    char *dot = strrchr(buf, '.');
    if (dot) *dot = '\0';
    return buf;
}

// Escape HTML special characters (<, >, &, ", ') into a caller-supplied buffer.
// Returns the number of bytes written (not counting the NUL terminator).
static int html_escape(char *out, int outsz, const char *in) {
    int n = 0;
    for (const char *p = in; *p; p++) {
        const char *esc;
        int elen;
        switch (*p) {
            case '&':  esc = "&amp;";  elen = 5; break;
            case '<':  esc = "&lt;";   elen = 4; break;
            case '>':  esc = "&gt;";   elen = 4; break;
            case '"':  esc = "&quot;"; elen = 6; break;
            case '\'': esc = "&#39;";  elen = 5; break;
            default:   esc = NULL;     elen = 1; break;
        }
        if (esc) {
            if (n + elen >= outsz - 1) break;
            memcpy(out + n, esc, elen);
            n += elen;
        } else {
            if (n >= outsz - 1) break;
            out[n++] = *p;
        }
    }
    out[n] = '\0';
    return n;
}

// Escape a string for safe embedding in a JSON string value.
// Escapes " and \ per RFC 8259; skips control chars (illegal in JSON strings).
static int json_escape(char *out, int outsz, const char *in) {
    int n = 0;
    for (const char *p = in; *p && n < outsz - 1; p++) {
        if (*p == '"' || *p == '\\') {
            if (n + 2 >= outsz - 1) break;
            out[n++] = '\\'; out[n++] = *p;
        } else if ((unsigned char)*p >= 0x20) {
            out[n++] = *p;
        }
        // control chars silently dropped
    }
    out[n] = '\0';
    return n;
}

static bool cover_exists(const char *image_path, char *cover_path_out, int outsz) {
    char base[MAX_PATH_LEN];
    basename_no_ext(image_path, base, sizeof(base));

    // Hard-cap the calculation. By subtracting 16, we leave plenty of 
    // guaranteed compile-time overhead for "0:/covers/" and ".jpeg" / ".png"
    int max_base_len = outsz - 16; 
    if (max_base_len < 0) {
        max_base_len = 0;
    }

    // 1. Try covers/ directory with EXT1
    // Adding an inline check directly in the snprintf argument forces GCC to recognize the absolute ceiling.
    snprintf(cover_path_out, outsz, "%s%.*s%s", WS_COVERS_DIR, 
             (max_base_len < outsz) ? max_base_len : 0, base, WS_COVER_EXT1);
    if (f_stat(cover_path_out, NULL) == FR_OK) return true;

    // 2. Try covers/ directory with EXT2
    snprintf(cover_path_out, outsz, "%s%.*s%s", WS_COVERS_DIR, 
             (max_base_len < outsz) ? max_base_len : 0, base, WS_COVER_EXT2);
    if (f_stat(cover_path_out, NULL) == FR_OK) return true;

    // Clear output buffer completely if no file was found
    if (outsz > 0) {
        cover_path_out[0] = '\0';
    }
    return false;
}


// Drive state name — aligned with drive_state_t (DRIVE_IDLE=0)
static const char *state_name(int state) {
    switch (state) {
        case 0: return "IDLE";    case 1: return "SPINUP";
        case 2: return "READY";   case 3: return "SEEKING";
        case 4: return "READING"; case 5: return "PLAYING";
        case 6: return "PAUSED";  case 7: return "ERROR";
        default: return "UNKNOWN";
    }
}

// SD card space via f_getfree. Returns false if the volume is not mounted.
static bool sd_get_space(uint64_t *used_out, uint64_t *total_out) {
    FATFS *fs;
    DWORD  fre_clust;
    if (f_getfree("0:", &fre_clust, &fs) != FR_OK) return false;
    uint64_t clust_bytes = (uint64_t)fs->csize * 512;
    uint64_t total       = (uint64_t)(fs->n_fatent - 2) * clust_bytes;
    uint64_t free_bytes  = (uint64_t)fre_clust * clust_bytes;
    *total_out = total;
    *used_out  = total - free_bytes;
    return true;
}

// Human-readable byte count: "X.X GB", "X.X MB", or "XXX KB"
static void fmt_bytes(char *buf, int bufsz, uint64_t bytes) {
    if (bytes >= (uint64_t)1024 * 1024 * 1024)
        snprintf(buf, bufsz, "%.1f GB", (double)bytes / (1024.0 * 1024 * 1024));
    else if (bytes >= (uint64_t)1024 * 1024)
        snprintf(buf, bufsz, "%.1f MB", (double)bytes / (1024.0 * 1024));
    else
        snprintf(buf, bufsz, "%lu KB", (unsigned long)(bytes / 1024));
}

// ---------------------------------------------------------------------------
// Cover art path cache — avoids up to 3 f_stat calls per image per HTML render
// ---------------------------------------------------------------------------
// Populated on demand and invalidated when the disc list changes.
// Sentinel: s_cover_cache[i][0] == '\1' means checked and not found.
#define WS_MAX_IMAGES 32
static char s_cover_cache[WS_MAX_IMAGES][256];
static bool s_cover_cache_valid = false;

static void refresh_cover_cache(void) {
    uint32_t n = s_image_count < WS_MAX_IMAGES ? s_image_count : WS_MAX_IMAGES;
    for (uint32_t i = 0; i < n; i++) {
        char path[256] = "";
        if (cover_exists(s_image_paths[i], path, sizeof(path)))
            strncpy(s_cover_cache[i], path, sizeof(s_cover_cache[i]));
        else
            s_cover_cache[i][0] = '\1';  // sentinel: checked, not found
    }
    s_cover_cache_valid = true;
}

